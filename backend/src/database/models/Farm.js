// Farm persistence model.
import mongoose from 'mongoose';

const farmSchema = new mongoose.Schema(
  {
    userId: { type: String, required: true, index: true },
    name: { type: String, required: true },
    location: { type: String, required: true },
    farmerName: { type: String, default: '' },
    farmerPhone: { type: String, default: '' },
    village: { type: String, default: '' },
    district: { type: String, default: '' },
    state: { type: String, default: '' },
    latitude: { type: Number, min: -90, max: 90 },
    longitude: { type: Number, min: -180, max: 180 },
    area: { type: Number, required: true },
    areaUnit: { type: String, default: 'acres' },
    landOwnership: { type: String, default: '' },
    soilType: { type: String, default: '' },
    soilPH: { type: Number, min: 0, max: 14 },
    soilEC: { type: Number, min: 0, max: 100 },
    soilOC: { type: Number, min: 0, max: 100 },
    soilN: { type: Number, min: 0 },
    soilP: { type: Number, min: 0 },
    soilK: { type: Number, min: 0 },
    soilS: { type: Number, min: 0 },
    soilZn: { type: Number, min: 0 },
    soilB: { type: Number, min: 0 },
    soilFe: { type: Number, min: 0 },
    soilCu: { type: Number, min: 0 },
    soilMn: { type: Number, min: 0 },
    soilSources: {
      soilPH: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilEC: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilOC: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilN: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilP: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilK: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilS: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilZn: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilB: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilFe: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilCu: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
      soilMn: { type: String, enum: ['soil_report_reviewed', 'farmer_entered'] },
    },
    soilTestDate: { type: String, default: '' },
    waterSource: { type: String, default: '' },
    waterAvailability: { type: String, default: '' },
    irrigationMethods: [{ type: String }],
    waterQuality: { type: String, default: '' },
    crops: [{ type: String }],
    season: { type: String, default: '' },
    previousCrop: { type: String, default: '' },
    cultivationMethod: { type: String, default: '' },
    images: [{ type: String }],
    healthScore: { type: Number, default: 75 },
    lastUpdated: { type: String, default: '' }
  },
  { timestamps: true }
);

export const Farm = mongoose.models.Farm || mongoose.model('Farm', farmSchema);
